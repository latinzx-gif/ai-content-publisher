            reason = "Milestone safety gate requires explicit human approval before real runtime execution."
            recommendedOption = runtime?.requiresApproval == false
                ? "Planning step may proceed now; keep destructive actions separately gated."
                : "Approve planning-only preparation now and require a second approval before any destructive action."
            requestType = "approval"
            linkedStage = "approval"
            intendedNextStep = "Approve the planning gate before future runtime launch."
        }

