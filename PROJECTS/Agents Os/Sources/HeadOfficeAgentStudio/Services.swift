    func transitionTask(id: UUID, to newStatus: String) {
        guard var task = tasks.first(where: { $0.id == id }) else { return }
        task.status = newStatus
        task.updatedAt = .now

        switch newStatus {
        case "awaiting_approval":
            task.resultSummary = "Runtime plan queued for launch approval."
            createRunLog(task: task, status: "awaiting_approval", summary: "Waiting for pre-launch approval.", stage: "approval-gate")
        case "launch_blocked":
            task.resultSummary = "Runtime launch blocked pending human decision."
            createRunLog(task: task, status: "launch_blocked", summary: "Launch blocked before execution.", stage: "launch-blocked")
        case "running":
            task.resultSummary = "Mock execution started."
            createRunLog(task: task, status: "running", summary: "Mock run started for \(task.title)", stage: "in_progress")
        case "review":
            task.resultSummary = "Implementation draft completed and waiting for review gate."
            createRunLog(task: task, status: "review", summary: "Task moved to review.", stage: "review")
        case "audit":
            task.resultSummary = "Review passed. Awaiting audit gate."
            createRunLog(task: task, status: "audit", summary: "Task moved to audit.", stage: "audit")
        case "done":
            task.resultSummary = "Audit passed. Task complete."
            createRunLog(task: task, status: "done", summary: "Audit passed.", stage: "done")
        case "need_fix":
            task.resultSummary = "Review or audit requested revisions."
            createRunLog(task: task, status: "need_fix", summary: "Task returned for fixes.", stage: "in_progress", errorSummary: "Additional revisions requested before the next gate.")
        case "blocked":
            task.resultSummary = "Waiting for human decision."
            createRunLog(task: task, status: "blocked", summary: "Task blocked pending human input.", stage: "open")
            _ = createHumanRequest(
                projectSlug: task.projectSlug,
                taskCode: task.taskCode,
                relatedTaskID: task.id,
                title: "Decision required for \(task.taskCode)",
                need: "Review scope, acceptance criteria, or external asset before continuing task \(task.title).",
                reason: "Manual checkpoint triggered from mock task loop.",
                priority: task.priority,
                requestType: "blocker",
                linkedStage: primaryStage(for: task),
                intendedNextStep: "Provide clarification or approval so work can resume.",
                recommendedOption: "Approve the next step or provide updated constraints."
            )
        case "cancelled":
            task.resultSummary = "Runtime plan cancelled before execution."
            createRunLog(task: task, status: "cancelled", summary: "Task plan cancelled.", stage: "open")
        default:
            task.resultSummary = "Reset to backlog."
            createRunLog(task: task, status: newStatus, summary: "Task reset to backlog.", stage: "open")
        }

        try? save(task)
        reloadAll()
    }

