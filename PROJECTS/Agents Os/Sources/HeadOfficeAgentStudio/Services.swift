        - Project Root: `\(project.createdFolderPath)`
        - Demo Script: `\(project.lastDemoScriptPath ?? "Not generated")`
        - Handoff Checklist: `\(project.lastHandoffChecklistPath ?? "Not generated")`
        - PRD Normalized: `\(project.prdNormalizedPath.isEmpty ? "Not imported" : project.prdNormalizedPath)`

        ## Known Limitations
        \(project.knownLimitations ?? "- Runtime execution remains manual/mock in V1.")

