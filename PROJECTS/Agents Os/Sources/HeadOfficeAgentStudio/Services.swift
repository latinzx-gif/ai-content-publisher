@MainActor
final class StudioStore: ObservableObject {
    @Published var projects: [StudioProject] = []
    @Published var agents: [AgentDefinition] = []
    @Published var skills: [SkillDefinition] = []
    @Published var teams: [TeamDefinition] = []
    @Published var runtimes: [RuntimeProfile] = []
    @Published var tasks: [StudioTask] = []
    @Published var runLogs: [TaskRunLog] = []
    @Published var humanRequests: [HumanRequestItem] = []
    @Published var demoItems: [DemoHandoffItem] = []
    @Published var bootstrapMessage = ""

    private let database: SQLiteJSONStore?

    init() {
        let initializedDatabase: SQLiteJSONStore?
        var initialMessage = ""

        do {
            initializedDatabase = try SQLiteJSONStore()
            initialMessage = "SQLite store ready"
        } catch {
            initializedDatabase = nil
            initialMessage = error.localizedDescription
        }

        self.database = initializedDatabase
        self.bootstrapMessage = initialMessage
        reloadAll()
        try? seedIfNeeded()
    }

    func reloadAll() {
        guard let database else { return }
        projects = ((try? database.loadAll(StudioProject.self)) ?? []).sorted { $0.updatedAt > $1.updatedAt }
        agents = ((try? database.loadAll(AgentDefinition.self)) ?? []).sorted { $0.name < $1.name }
        skills = ((try? database.loadAll(SkillDefinition.self)) ?? []).sorted { $0.name < $1.name }
        teams = ((try? database.loadAll(TeamDefinition.self)) ?? []).sorted { $0.name < $1.name }
        runtimes = ((try? database.loadAll(RuntimeProfile.self)) ?? []).sorted { $0.name < $1.name }
        tasks = ((try? database.loadAll(StudioTask.self)) ?? []).sorted { $0.createdAt < $1.createdAt }
        runLogs = ((try? database.loadAll(TaskRunLog.self)) ?? []).sorted { $0.startedAt > $1.startedAt }
        humanRequests = ((try? database.loadAll(HumanRequestItem.self)) ?? []).sorted { $0.createdAt > $1.createdAt }
        demoItems = ((try? database.loadAll(DemoHandoffItem.self)) ?? []).sorted { $0.createdAt < $1.createdAt }
    }

    func createProject(
        name: String,
        projectType: String,
        clientLabel: String,
        deadline: Date,
        priority: String,
        outputGoal: String,
        baseFolderPath: String
    ) throws -> StudioProject {
        let slug = Slugifier.slug(from: name)
        var project = StudioProject(
            name: name,
            slug: slug,
            projectType: projectType,
            clientLabel: clientLabel,
            deadline: deadline,
            priority: priority,
            outputGoal: outputGoal,
            baseFolderPath: baseFolderPath,
            createdFolderPath: "",
            status: "draft",
            currentMilestone: "Project Setup",
            prdOriginalPath: "",
            prdNormalizedPath: "",
            notes: "",
            knownLimitations: nil,
            lastDemoScriptPath: nil,
            lastHandoffChecklistPath: nil,
            lastClosureSummaryPath: nil,
            createdAt: .now,
            updatedAt: .now
        )
        let createdPath = try FolderGeneratorService.createProjectFolders(for: project)
        project.createdFolderPath = createdPath
