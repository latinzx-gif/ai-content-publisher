        reloadAll()
        return closureURL.path
    }

    func attemptCloseProject(projectID: UUID) throws -> String {
        guard let project = projects.first(where: { $0.id == projectID }) else {
            throw NSError(domain: "HeadOfficeAgentStudio", code: 404, userInfo: [NSLocalizedDescriptionKey: "Project not found"])
