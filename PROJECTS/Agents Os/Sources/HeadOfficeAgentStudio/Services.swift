enum Slugifier {
    static func slug(from input: String) -> String {
        let lowered = input.lowercased()
        let pattern = "[^a-z0-9]+"
        let regex = try? NSRegularExpression(pattern: pattern)
        let range = NSRange(location: 0, length: lowered.utf16.count)
        let hyphenated = regex?.stringByReplacingMatches(in: lowered, options: [], range: range, withTemplate: "-") ?? lowered
        return hyphenated.trimmingCharacters(in: CharacterSet(charactersIn: "-"))
    }
}

enum FolderGeneratorService {
    static func createProjectFolders(for project: StudioProject) throws -> String {
        let fileManager = FileManager.default
        let basePath = StudioPaths.expanded(project.baseFolderPath)
        let projectRoot = URL(fileURLWithPath: basePath, isDirectory: true)
            .appendingPathComponent(project.slug, isDirectory: true)

        try fileManager.createDirectory(at: projectRoot, withIntermediateDirectories: true)
        for folder in StudioPaths.folderTemplate {
            try fileManager.createDirectory(
                at: projectRoot.appendingPathComponent(folder, isDirectory: true),
                withIntermediateDirectories: true
            )
        }

        let bootstrapReadme = projectRoot.appendingPathComponent("README.md")
        if !fileManager.fileExists(atPath: bootstrapReadme.path) {
            let content = "# \(project.name)\n\nGenerated by Head Office Agent Studio.\n\nStatus: \(project.status)\n"
            try content.write(to: bootstrapReadme, atomically: true, encoding: .utf8)
        }

        return projectRoot.path
    }

    static func workspaceHealth(for project: StudioProject) -> ProjectWorkspaceHealthReport {
        let fileManager = FileManager.default
        let projectRootPath = resolvedProjectRootPath(for: project)
        let projectRoot = URL(fileURLWithPath: projectRootPath, isDirectory: true)
        let rootExists = fileManager.fileExists(atPath: projectRoot.path)

        var existingFolders: [String] = []
        var missingFolders: [String] = []

        for folder in StudioPaths.folderTemplate {
            let folderPath = projectRoot.appendingPathComponent(folder, isDirectory: true).path
            var isDirectory: ObjCBool = false
            if fileManager.fileExists(atPath: folderPath, isDirectory: &isDirectory), isDirectory.boolValue {
                existingFolders.append(folder)
            } else {
                missingFolders.append(folder)
            }
        }

        let readmeExists = fileManager.fileExists(atPath: projectRoot.appendingPathComponent("README.md").path)

        return ProjectWorkspaceHealthReport(
            projectRootPath: projectRoot.path,
            rootExists: rootExists,
            existingFolders: existingFolders,
            missingFolders: missingFolders,
            readmeExists: readmeExists
        )
    }

    @discardableResult
    static func repairProjectFolders(for project: StudioProject) throws -> ProjectWorkspaceHealthReport {
        let fileManager = FileManager.default
        let projectRoot = URL(fileURLWithPath: resolvedProjectRootPath(for: project), isDirectory: true)

        try fileManager.createDirectory(at: projectRoot, withIntermediateDirectories: true)
        for folder in StudioPaths.folderTemplate {
            try fileManager.createDirectory(
                at: projectRoot.appendingPathComponent(folder, isDirectory: true),
                withIntermediateDirectories: true
            )
        }

        let bootstrapReadme = projectRoot.appendingPathComponent("README.md")
        if !fileManager.fileExists(atPath: bootstrapReadme.path) {
            let content = "# \(project.name)\n\nGenerated by Head Office Agent Studio.\n\nStatus: \(project.status)\n"
            try content.write(to: bootstrapReadme, atomically: true, encoding: .utf8)
        }

        return workspaceHealth(for: project)
    }

    private static func resolvedProjectRootPath(for project: StudioProject) -> String {
        if !project.createdFolderPath.isEmpty {
            return StudioPaths.expanded(project.createdFolderPath)
        }

        return URL(fileURLWithPath: StudioPaths.expanded(project.baseFolderPath), isDirectory: true)
            .appendingPathComponent(project.slug, isDirectory: true)
            .path
    }
}

