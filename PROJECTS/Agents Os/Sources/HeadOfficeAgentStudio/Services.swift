            projectSlug: refreshedProject.slug,
            itemType: "handoff",
            title: "Project closure gate",
            details: "Project closed after closure summary export and zero blocking requests.",
            owner: "Handoff Agent",
            artifactPath: closurePath,
            status: "done"
        )
        reloadAll()
        return "Project \(project.name) closed. Closure summary exported to \(closurePath)"
    }

