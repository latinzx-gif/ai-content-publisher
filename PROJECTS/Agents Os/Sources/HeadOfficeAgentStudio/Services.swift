    private func createRunLog(
        task: StudioTask,
        status: String,
        summary: String,
        stage: String,
        artifactPath: String? = nil,
        relatedRequest: HumanRequestItem? = nil,
        errorSummary: String? = nil
    ) {
        var sections = [
            "[\(DateFormatter.studioTimestamp.string(from: .now))] Stage: \(stage)",
            "Task: \(task.taskCode) - \(task.title)",
            "Project: \(task.projectSlug)",
            "Runtime: \(task.runtimeName)"
        ]

        if let artifactPath, !artifactPath.isEmpty {
            sections.append("Artifact: \(artifactPath)")
        }
        if let relatedRequest {
            sections.append("Related Request: \(relatedRequest.title)")
        }
        if let errorSummary, !errorSummary.isEmpty {
            sections.append("Error: \(errorSummary)")
        }

        sections.append("")
        sections.append("This is a manual/mock task loop entry for V1.")
        sections.append("No autonomous agent execution has been performed.")

        let log = TaskRunLog(
            projectSlug: task.projectSlug,
            taskCode: task.taskCode,
            taskTitle: task.title,
            runtimeName: task.runtimeName,
            status: status,
            summary: summary,
            logText: sections.joined(separator: "\n"),
            stage: stage,
            artifactPath: artifactPath,
            relatedRequestID: relatedRequest?.id,
            relatedRequestTitle: relatedRequest?.title,
            errorSummary: errorSummary,
            startedAt: .now,
            endedAt: .now
        )
        try? save(log)
    }

