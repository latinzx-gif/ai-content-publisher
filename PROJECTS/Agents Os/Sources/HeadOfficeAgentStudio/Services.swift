            requestTitle = "Scope confirmation needed for \(task.taskCode)"
            need = "Confirm that runtime work must stay inside `\(project.createdFolderPath)` and list any extra allowed files before execution."
            reason = "Runtime brief requires explicit allowed/forbidden path contract before a future launch."
            recommendedOption = "Approve project-root-only scope, or provide an exact additional allowlist."
            requestType = "scope"
            linkedStage = "open"
            intendedNextStep = "Confirm path scope before any launch or artifact generation."
