    private static func normalizePRD(sourceURL: URL) -> String {
        let ext = sourceURL.pathExtension.lowercased()
        let header = "# Normalized PRD\n\nImported from: \(sourceURL.lastPathComponent)\n\n"

        if ["md", "markdown", "txt"].contains(ext),
           let content = try? String(contentsOf: sourceURL, encoding: .utf8) {
            return header + content
        }

        if ["html", "htm", "rtf", "doc", "docx"].contains(ext),
           let content = extractUsingTextUtil(sourceURL: sourceURL) {
            return header + content
        }

        if ext == "pdf", let content = extractPDFText(sourceURL: sourceURL) {
            return header + content
        }

        if ext == "html",
           let content = try? String(contentsOf: sourceURL, encoding: .utf8) {
            return header + "```html\n" + content + "\n```\n"
        }

        return header + """
        This file type requires manual review in V1.

        - Original path: \(sourceURL.path)
        - Extension: \(ext.isEmpty ? "unknown" : ext)
        - Action: open the original file and paste/extract the important sections into this markdown file.
        """
    }

    private static func extractUsingTextUtil(sourceURL: URL) -> String? {
        runProcess(executable: "/usr/bin/textutil", arguments: ["-convert", "txt", "-stdout", sourceURL.path])
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .nonEmpty
    }

    private static func extractPDFText(sourceURL: URL) -> String? {
        let script = """
from pypdf import PdfReader
import sys
reader = PdfReader(sys.argv[1])
chunks = []
for page in reader.pages:
    chunks.append(page.extract_text() or '')
print('\\n'.join(chunks))
"""
        return runProcess(executable: "/usr/bin/python3", arguments: ["-c", script, sourceURL.path])
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .nonEmpty
    }

    private static func runProcess(executable: String, arguments: [String]) -> String {
        let process = Process()
        process.executableURL = URL(fileURLWithPath: executable)
        process.arguments = arguments

        let outputPipe = Pipe()
        let errorPipe = Pipe()
        process.standardOutput = outputPipe
        process.standardError = errorPipe

        do {
            try process.run()
            process.waitUntilExit()
            let outputData = outputPipe.fileHandleForReading.readDataToEndOfFile()
            let errorData = errorPipe.fileHandleForReading.readDataToEndOfFile()
            if process.terminationStatus == 0, let output = String(data: outputData, encoding: .utf8) {
                return output
            }
            if let errorText = String(data: errorData, encoding: .utf8), !errorText.isEmpty {
                return errorText
            }
        } catch {
            return ""
        }

        return ""
    }

    private static func detectRoles(in text: String) -> [String] {
        detectMatches(in: text, keywords: ["admin", "manager", "staff", "user", "client", "operator", "customer", "owner", "agent"])
    }

    private static func detectModules(in text: String) -> [String] {
        let headings = text
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { $0.hasPrefix("#") || $0.lowercased().hasPrefix("module") || $0.lowercased().hasPrefix("feature") }
        return Array(NSOrderedSet(array: headings)) as? [String] ?? []
    }

    private static func detectRiskLines(in text: String) -> [String] {
        text
            .components(separatedBy: .newlines)
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter {
                let lower = $0.lowercased()
                return !lower.isEmpty && (lower.contains("risk") || lower.contains("block") || lower.contains("dependency") || lower.contains("assumption"))
            }
    }

    private static func detectMatches(in text: String, keywords: [String]) -> [String] {
        let lines = text.components(separatedBy: .newlines)
        var matches: [String] = []
        for line in lines {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
            let lower = trimmed.lowercased()
            guard !trimmed.isEmpty else { continue }
            if keywords.contains(where: { lower.contains($0) }) {
                matches.append(trimmed)
            }
        }
        return Array(NSOrderedSet(array: matches)) as? [String] ?? []
    }
}

private extension String {
    var nonEmpty: String? {
        let trimmed = trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? nil : trimmed
    }
}

final class SQLiteJSONStore {
    private var db: OpaquePointer?
    private let encoder = JSONEncoder()
    private let decoder = JSONDecoder()
    private let databaseURL: URL

    init() throws {
        let supportDirectory = try Self.makeSupportDirectory()
        databaseURL = supportDirectory.appendingPathComponent("HeadOfficeAgentStudio.sqlite")
        try openDatabase()
        try createSchema()
        encoder.dateEncodingStrategy = .iso8601
        decoder.dateDecodingStrategy = .iso8601
    }

    deinit {
        sqlite3_close(db)
    }

    func loadAll<Record: StudioRecord>(_ type: Record.Type) throws -> [Record] {
        let query = "SELECT payload FROM records WHERE type = ? ORDER BY updated_at DESC;"
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(db, query, -1, &statement, nil) == SQLITE_OK else {
            throw databaseError(message: "Failed to prepare load statement")
        }
        defer { sqlite3_finalize(statement) }

        sqlite3_bind_text(statement, 1, Record.recordType, -1, SQLITE_TRANSIENT)

        var results: [Record] = []
        while sqlite3_step(statement) == SQLITE_ROW {
            guard let text = sqlite3_column_text(statement, 0) else { continue }
            let payload = String(cString: text)
            let data = Data(payload.utf8)
            results.append(try decoder.decode(Record.self, from: data))
        }
        return results
    }

    func save<Record: StudioRecord>(_ record: Record) throws {
        let query = "INSERT INTO records(type, id, payload, updated_at) VALUES (?, ?, ?, ?) ON CONFLICT(type, id) DO UPDATE SET payload = excluded.payload, updated_at = excluded.updated_at;"
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(db, query, -1, &statement, nil) == SQLITE_OK else {
            throw databaseError(message: "Failed to prepare save statement")
        }
        defer { sqlite3_finalize(statement) }

        let payloadData = try encoder.encode(record)
        let payload = String(decoding: payloadData, as: UTF8.self)

        sqlite3_bind_text(statement, 1, Record.recordType, -1, SQLITE_TRANSIENT)
        sqlite3_bind_text(statement, 2, record.id.uuidString, -1, SQLITE_TRANSIENT)
        sqlite3_bind_text(statement, 3, payload, -1, SQLITE_TRANSIENT)
        sqlite3_bind_double(statement, 4, Date().timeIntervalSince1970)

        guard sqlite3_step(statement) == SQLITE_DONE else {
            throw databaseError(message: "Failed to save record")
        }
    }

    func delete<Record: StudioRecord>(_ record: Record) throws {
        let query = "DELETE FROM records WHERE type = ? AND id = ?;"
        var statement: OpaquePointer?
        guard sqlite3_prepare_v2(db, query, -1, &statement, nil) == SQLITE_OK else {
            throw databaseError(message: "Failed to prepare delete statement")
        }
        defer { sqlite3_finalize(statement) }

        sqlite3_bind_text(statement, 1, Record.recordType, -1, SQLITE_TRANSIENT)
        sqlite3_bind_text(statement, 2, record.id.uuidString, -1, SQLITE_TRANSIENT)

        guard sqlite3_step(statement) == SQLITE_DONE else {
            throw databaseError(message: "Failed to delete record")
        }
    }

    private func openDatabase() throws {
        guard sqlite3_open(databaseURL.path, &db) == SQLITE_OK else {
            throw databaseError(message: "Unable to open SQLite database at \(databaseURL.path)")
        }
    }

    private func createSchema() throws {
        let schema = """
        CREATE TABLE IF NOT EXISTS records (
            type TEXT NOT NULL,
            id TEXT NOT NULL,
            payload TEXT NOT NULL,
            updated_at REAL NOT NULL,
            PRIMARY KEY (type, id)
        );
        """
        guard sqlite3_exec(db, schema, nil, nil, nil) == SQLITE_OK else {
            throw databaseError(message: "Unable to create records table")
        }
    }

    private func databaseError(message: String) -> NSError {
        let details = db.flatMap { sqlite3_errmsg($0) }.map { String(cString: $0) } ?? "Unknown SQLite error"
        return NSError(domain: "HeadOfficeAgentStudio.SQLite", code: 1, userInfo: [NSLocalizedDescriptionKey: "\(message): \(details)"])
    }

    private static func makeSupportDirectory() throws -> URL {
        let support = try FileManager.default.url(for: .applicationSupportDirectory, in: .userDomainMask, appropriateFor: nil, create: true)
        let directory = support.appendingPathComponent("HeadOfficeAgentStudio", isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        return directory
    }
}

