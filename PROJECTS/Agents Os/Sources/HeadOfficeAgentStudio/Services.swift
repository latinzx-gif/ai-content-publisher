    func approveHumanRequest(id: UUID, response: String) {
        guard var request = humanRequests.first(where: { $0.id == id }) else { return }
        request.status = "resolved"
        request.userResponse = response
        request.updatedAt = .now
        try? save(request)

        if let task = linkedTask(for: request) {
            switch request.requestType ?? "blocker" {
            case "review":
                _ = moveTaskToAudit(taskID: task.id, queueGate: true)
            case "audit":
                transitionTask(id: task.id, to: "done")
            case "approval", "scope", "auth", "blocker":
                transitionTask(id: task.id, to: "running")
            default:
                transitionTask(id: task.id, to: "running")
            }
        }

        reloadAll()
    }

