        \(demoChecklist.isEmpty ? "- None" : demoChecklist)

        ## Open Tasks
        \(openTaskLines)

        ## Blocking Requests
        \(blockingLines)

        ## Recent Run Log Highlights
        \(recentLogLines)
        """
