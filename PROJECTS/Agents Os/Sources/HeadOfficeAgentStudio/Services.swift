        # Closure Summary — \(project.name)

        ## Project Snapshot
        - Status: \(project.status)
        - Milestone: \(project.currentMilestone)
        - Client / Owner: \(project.clientLabel)
        - Deadline: \(DateFormatter.studioDate.string(from: project.deadline))
